-- Firma Bilgileri: il, ilçe ve il düzeyindeki vergi dairesi bağlantıları.
-- Referanslar: kullanıcının il/ilçe Excel'i ve GİB'in 18.06.2026 tarihli resmî PDF'i.
-- Mevcut firma adı, adresi ve yazılı vergi dairesi bilgisi değiştirilmez.
-- Eski firmalara il/ilçe/vergi dairesi kodu otomatik atanmaz.
-- Tamamını tek parça çalıştırın; ikinci kez çalıştırılabilir.
BEGIN;

CREATE TABLE IF NOT EXISTS public.firma_referans_illeri (
  il_id integer PRIMARY KEY CHECK (il_id > 0),
  il_kodu text NOT NULL UNIQUE CHECK (il_kodu ~ '^[0-9]{2}$' AND il_kodu = lpad(il_id::text,2,'0')),
  il_adi text NOT NULL CHECK (btrim(il_adi) <> '')
);
CREATE TABLE IF NOT EXISTS public.firma_referans_ilceleri (
  ilce_id integer PRIMARY KEY CHECK (ilce_id > 0),
  il_id integer NOT NULL REFERENCES public.firma_referans_illeri(il_id),
  ilce_adi text NOT NULL CHECK (btrim(ilce_adi) <> ''),
  UNIQUE (il_id, ilce_id)
);
CREATE TABLE IF NOT EXISTS public.firma_referans_vergi_daireleri (
  vergi_dairesi_kodu text PRIMARY KEY CHECK (vergi_dairesi_kodu ~ '^[0-9]{5}$'),
  il_id integer NOT NULL REFERENCES public.firma_referans_illeri(il_id),
  vergi_dairesi_adi text NOT NULL CHECK (btrim(vergi_dairesi_adi) <> ''),
  tur text NOT NULL CHECK (tur IN ('vergi_dairesi_mudurlugu','defterdarlik')),
  kaynak_belge_tarihi date NOT NULL,
  UNIQUE (il_id, vergi_dairesi_kodu),
  CHECK (left(vergi_dairesi_kodu,2) = lpad(il_id::text,2,'0'))
);

